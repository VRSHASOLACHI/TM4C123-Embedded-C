#include "tm4c123gh6pm.h"
#include <stdint.h>
#include "PLL.h"
#define MAX_X 84
#define MAX_Y 48
#define CONTRAST 0xB1
#define SCREENW 84
#define SCREENH 48
#define DC (*((volatile uint32_t *)0x40004100))
#define DC_COMMAND 0
#define DC_DATA 0x40
#define RESET (*((volatile uint32_t *)0x40004200))
#define RESET_LOW 0
#define RESET_HIGH 0x80

enum typeOfWrite{
  COMMAND,
  DATA
};

void static lcdwrite(enum typeOfWrite type, uint8_t message){
  if(type == COMMAND){
    while((SSI0_SR_R&0x00000010)==0x00000010){};
    DC = DC_COMMAND;
    SSI0_DR_R = message;
    while((SSI0_SR_R&0x00000010)==0x00000010){};
  } else{
    while((SSI0_SR_R&0x00000002)==0){};
    DC = DC_DATA;
    SSI0_DR_R = message;
  }
}
void static lcddatawrite(uint8_t data){
  while((SSI0_SR_R&0x00000002)==0){};
  DC = DC_DATA;
  SSI0_DR_R = data;
}
void Nokia5110_Init(void){
  volatile uint32_t delay;
  SYSCTL_RCGC1_R |= 0x00000010;
  SYSCTL_RCGC2_R |= 0x00000001;
  delay = SYSCTL_RCGC2_R;
  GPIO_PORTA_DIR_R |= 0xC0;
  GPIO_PORTA_AFSEL_R |= 0x2C;
  GPIO_PORTA_AFSEL_R &= ~0xC0;
  GPIO_PORTA_DEN_R |= 0xEC;
  GPIO_PORTA_PCTL_R = (GPIO_PORTA_PCTL_R&0xFF0F00FF)+0x00202200;
  GPIO_PORTA_PCTL_R = (GPIO_PORTA_PCTL_R&0x00FFFFFF)+0x00000000;
  GPIO_PORTA_AMSEL_R &= ~0xEC;
  SSI0_CR1_R &= ~(0x00000002);
  SSI0_CR1_R &= ~(0x00000004);
  SSI0_CC_R &= ~(0x0000000F);
  SSI0_CPSR_R = (SSI0_CPSR_R&~(0x000000FF))+24;
  SSI0_CR0_R &= ~(0x0000FFF0);
  SSI0_CR0_R |= 0x00000007;
  SSI0_CR1_R |= 0x00000002;
  RESET = RESET_LOW;
  for(delay=0; delay<10; delay=delay+1);
  RESET = RESET_HIGH;
  lcdwrite(COMMAND, 0x21);
  lcdwrite(COMMAND, CONTRAST);
  lcdwrite(COMMAND, 0x04);
  lcdwrite(COMMAND, 0x14);
  lcdwrite(COMMAND, 0x20);
  lcdwrite(COMMAND, 0x0C);
}

void Nokia5110_SetCursor(uint8_t newX, uint8_t newY){
  if((newX > 11) || (newY > 5)){
    return;
  }
  lcdwrite(COMMAND, 0x80|(newX*7));
  lcdwrite(COMMAND, 0x40|newY);
}

void Nokia5110_Clear(void){
  int i;
  for(i=0; i<(MAX_X*MAX_Y/8); i=i+1){
    lcddatawrite(0x00);
  }
  Nokia5110_SetCursor(0, 0);
}

void Nokia5110_DrawFullImage(const uint8_t *ptr){
  int i;
  Nokia5110_SetCursor(0, 0);
  for(i=0; i<(MAX_X*MAX_Y/8); i=i+1){
    lcddatawrite(ptr[i]);
  }
}
